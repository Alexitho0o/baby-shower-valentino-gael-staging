const CONTROLLED_TURNSTILE_ERRORS =
  new Set([
    "TURNSTILE_API_LOAD_FAILED",
    "TURNSTILE_API_UNAVAILABLE",
    "TURNSTILE_CONTAINER_NOT_FOUND",
    "TURNSTILE_RENDER_FAILED",
    "TURNSTILE_EXECUTION_FAILED",
    "TURNSTILE_INVALID_TOKEN",
    "TURNSTILE_ERROR",
    "TURNSTILE_EXPIRED",
    "TURNSTILE_TIMEOUT",
    "TURNSTILE_UNSUPPORTED",
  ]);

const CONTROLLED_GATEWAY_ERRORS =
  new Set([
    "TURNSTILE_REJECTED",
    "TURNSTILE_ACTION_MISMATCH",
    "TURNSTILE_HOSTNAME_MISMATCH",
    "TURNSTILE_UNAVAILABLE",
    "TURNSTILE_SITEVERIFY_TIMEOUT",
    "TURNSTILE_SITEVERIFY_NETWORK_ERROR",
    "TURNSTILE_SITEVERIFY_HTTP_ERROR",
    "TURNSTILE_SITEVERIFY_INVALID_RESPONSE",
    "TURNSTILE_SITEVERIFY_MISSING_SECRET",
    "TURNSTILE_SITEVERIFY_INVALID_SECRET",
    "TURNSTILE_SITEVERIFY_MISSING_RESPONSE",
    "TURNSTILE_SITEVERIFY_INVALID_TOKEN",
    "TURNSTILE_SITEVERIFY_BAD_REQUEST",
    "TURNSTILE_SITEVERIFY_TIMEOUT_OR_DUPLICATE",
    "TURNSTILE_SITEVERIFY_INTERNAL_ERROR",
    "TURNSTILE_SERVER_CONFIGURATION_ERROR",
    "GATEWAY_REQUEST_REJECTED",
    "GATEWAY_TIMEOUT",
    "GATEWAY_UNAVAILABLE",
    "IDEMPOTENCY_CONFLICT",
    "RSVP_VALIDATION_FAILED",
    "GIFT_UNAVAILABLE",
  ]);

const CONTROLLED_TURNSTILE_CLIENT_CODE_PATTERN =
  /^TURNSTILE_CLIENT_[0-9]{3,8}$/;

export const isControlledDiagnosticCode = (
  code,
) => (
  typeof code === "string"
  && (
    CONTROLLED_TURNSTILE_ERRORS.has(code)
    || CONTROLLED_GATEWAY_ERRORS.has(code)
    || CONTROLLED_TURNSTILE_CLIENT_CODE_PATTERN
      .test(code)
  )
);

export const normalizeDiagnosticCode = (
  code,
) => (
  isControlledDiagnosticCode(code)
    ? code
    : ""
);
